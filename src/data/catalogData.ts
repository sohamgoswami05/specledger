export interface PriceHistoryRecord {
  phone_id: string;
  store: 'flipkart';
  price_inr: number;
  in_stock: boolean;
  recorded_at: string;
  event?: string;
}

/**
 * Generates a single current baseline snapshot (dated today) rather than
 * synthetic 365-day festival dips, ready for real historical anchors & Dec 1+ daily scrapes.
 */
export function generateBaselineSnapshot(
  phoneId: string,
  currentPrice: number
): PriceHistoryRecord[] {
  const todayStr = new Date().toISOString().split('T')[0];
  return [
    {
      phone_id: phoneId,
      store: 'flipkart',
      price_inr: currentPrice,
      in_stock: true,
      recorded_at: todayStr,
      event: 'Current Baseline',
    },
  ];
}
